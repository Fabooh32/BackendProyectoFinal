-- G08 · Cabanas «Bosque Nativo»
-- Crea las cinco tablas del negocio en TU esquema de Oracle (FreeSQL).
-- Se puede ejecutar de nuevo: primero borra las tablas si ya existen
-- (OJO: al hacerlo se pierden sus datos).
--
-- Tablas:  huespedes, cabanas, servicios_extra   (maestras)
--          reservas                              (entidad principal, con estados)
--          detalle_servicio                      (detalle, clave primaria compuesta)

DROP TABLE IF EXISTS detalle_servicio CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS reservas         CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS servicios_extra  CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS cabanas          CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS huespedes        CASCADE CONSTRAINTS PURGE;

-- IDENTITY: Oracle numera solo la clave primaria (el AUTO_INCREMENT de MySQL).
-- NOCACHE: sin el, FreeSQL puede saltar de 1 a 21 entre conexiones.
-- Las fechas con hora (TIMESTAMP) se guardan en UTC, que es lo que espera Django.
-- fecha_llegada y fecha_salida son DATE: solo importa el dia, no la hora.

-- Maestra 1: quien reserva. El documento es el RUT (chilenos) o el pasaporte (extranjeros).
CREATE TABLE huespedes (
    id_huesped     NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    documento      VARCHAR2(20)  NOT NULL,
    nombre         VARCHAR2(120) NOT NULL,
    email          VARCHAR2(100) NOT NULL,
    telefono       VARCHAR2(20),
    pais           VARCHAR2(60)  NOT NULL,
    fecha_registro TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_huespedes         PRIMARY KEY (id_huesped),
    CONSTRAINT uq_huespedes_documento UNIQUE (documento),
    CONSTRAINT uq_huespedes_email     UNIQUE (email)
);

-- Maestra 2: las cabanas del complejo.
-- Oracle no tiene un tipo booleano que Django use: activo es 1 o 0.
CREATE TABLE cabanas (
    id_cabana   NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    codigo      VARCHAR2(20)  NOT NULL,
    nombre      VARCHAR2(100) NOT NULL,
    descripcion CLOB,
    capacidad   NUMBER(3)     NOT NULL,
    valor_noche NUMBER(10,2)  NOT NULL,
    activo      NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_cabanas           PRIMARY KEY (id_cabana),
    CONSTRAINT uq_cabanas_codigo    UNIQUE (codigo),
    CONSTRAINT ck_cabanas_capacidad CHECK (capacidad > 0),
    CONSTRAINT ck_cabanas_valor     CHECK (valor_noche >= 0),
    CONSTRAINT ck_cabanas_activo    CHECK (activo IN (0, 1))
);

-- Maestra 3: servicios adicionales (tinaja, desayuno, lena...).
CREATE TABLE servicios_extra (
    id_servicio NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    nombre      VARCHAR2(80)  NOT NULL,
    descripcion VARCHAR2(200),
    precio      NUMBER(10,2)  NOT NULL,
    CONSTRAINT pk_servicios_extra    PRIMARY KEY (id_servicio),
    CONSTRAINT uq_servicios_nombre   UNIQUE (nombre),
    CONSTRAINT ck_servicios_precio   CHECK (precio >= 0)
);

-- Entidad principal. Oracle no tiene ENUM: el estado se limita con un CHECK.
-- Estados: pendiente -> confirmada -> finalizada
--          pendiente / confirmada -> cancelada
-- Las reglas R1 (no cruzar fechas) y R2 (capacidad) viven en los casos de uso,
-- pero la estadia minima de 2 noches (R3) tambien se protege aqui con un CHECK.
CREATE TABLE reservas (
    id_reserva     NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    id_huesped     NUMBER(11) NOT NULL,
    id_cabana      NUMBER(11) NOT NULL,
    fecha_llegada  DATE       NOT NULL,
    fecha_salida   DATE       NOT NULL,
    n_personas     NUMBER(3)  NOT NULL,
    total          NUMBER(12,2) DEFAULT 0 NOT NULL,
    estado         VARCHAR2(10) DEFAULT 'pendiente' NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_reservas         PRIMARY KEY (id_reserva),
    CONSTRAINT fk_reservas_huesped FOREIGN KEY (id_huesped) REFERENCES huespedes (id_huesped),
    CONSTRAINT fk_reservas_cabana  FOREIGN KEY (id_cabana)  REFERENCES cabanas (id_cabana),
    CONSTRAINT ck_reservas_estado  CHECK (estado IN ('pendiente', 'confirmada', 'finalizada', 'cancelada')),
    CONSTRAINT ck_reservas_personas CHECK (n_personas > 0),
    CONSTRAINT ck_reservas_total   CHECK (total >= 0),
    CONSTRAINT ck_reservas_fechas  CHECK (fecha_salida >= fecha_llegada + 2)
);

-- Detalle: sin id propio, la clave es la pareja (id_reserva, id_servicio).
-- subtotal es una columna VIRTUAL: Oracle la calcula al leerla.
-- Si se borra una reserva (solo se permite en estado inicial), sus lineas se borran con ella.
CREATE TABLE detalle_servicio (
    id_reserva      NUMBER(11)   NOT NULL,
    id_servicio     NUMBER(11)   NOT NULL,
    cantidad        NUMBER(11)   NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,
    subtotal        NUMBER(12,2) GENERATED ALWAYS AS (cantidad * precio_unitario) VIRTUAL,
    CONSTRAINT pk_detalle_servicio  PRIMARY KEY (id_reserva, id_servicio),
    CONSTRAINT fk_detalle_reserva   FOREIGN KEY (id_reserva)  REFERENCES reservas (id_reserva) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_servicio  FOREIGN KEY (id_servicio) REFERENCES servicios_extra (id_servicio),
    CONSTRAINT ck_detalle_cantidad  CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio    CHECK (precio_unitario >= 0)
);

-- Indices para las claves foraneas (MySQL los crea solo; Oracle no)
CREATE INDEX ix_reservas_huesped    ON reservas (id_huesped);
CREATE INDEX ix_reservas_cabana     ON reservas (id_cabana);
CREATE INDEX ix_detalle_servicio    ON detalle_servicio (id_servicio);

-- Indice extra: acelera la busqueda de fechas cruzadas (R1) y el reporte de ocupacion
CREATE INDEX ix_reservas_fechas     ON reservas (id_cabana, fecha_llegada, fecha_salida);